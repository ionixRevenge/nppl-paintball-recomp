#!/usr/bin/env python3
"""Generate build.ninja for the NPPL Championship Paintball 2009 decomp.

Pipeline:
  splat (config/slus_218.55.yaml) -> asm/ + src/ + build/SLUS_218.55.ld
  each object -> assembled (asm) or compiled (decompiled C)
  ld -> build/SLUS_218.55.elf -> objcopy -> build/main.bin
  tools/compare.py checks build/main.bin against the original main segment.

C files:
  By default every src/*.c translation unit is still built from its full
  disassembly (asm/<name>.s), so the build always round-trips byte-for-byte.
  Pass --cc to compile real C instead:
    --cc "path/to/mwccps2.exe"      matching build (needs MWCC 2.4.1-era compiler)
    --cc "mips64r5900el-ps2-elf-gcc" non-matching build (functional, for porting)
"""
import argparse, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
YAML = "config/slus_218.55.yaml"
LD_SCRIPT = "build/SLUS_218.55.ld"
TARGET = "iso/SLUS_218.55"

def find_cross(prefix_dir):
    p = os.path.join(prefix_dir, "mips64r5900el-ps2-elf-")
    return p.replace("\\", "/")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--toolchain", default=os.environ.get("PS2DEV_EE_BIN", "tools/ps2dev/ee/bin"))
    ap.add_argument("--cc", default=None, help="C compiler for src/*.c (default: use full asm)")
    ap.add_argument("--cflags", default="-O2 -G0 -Iinclude")
    ap.add_argument("--no-split", action="store_true", help="don't re-run splat")
    a = ap.parse_args()
    os.chdir(ROOT)

    py = sys.executable.replace("\\", "/")
    # Verify + extract the user's ISO from game_iso/ (no game data ships with the repo)
    subprocess.check_call([py, "tools/setup_iso.py"])
    if not a.no_split or not os.path.exists(LD_SCRIPT):
        subprocess.check_call([py, "-m", "splat", "split", YAML])

    x = find_cross(a.toolchain)
    ld_text = open(LD_SCRIPT).read()
    objs = re.findall(r"(build/[^\s()]+\.o)", ld_text)
    objs = list(dict.fromkeys(objs))

    n = []
    w = n.append
    w("# generated by configure.py - do not edit")
    w(f"as = {x}as")
    w(f"ld = {x}ld")
    w(f"objcopy = {x}objcopy")
    w(f"python = {py}")
    w("asflags = -EL -march=r5900 -mabi=eabi -G0 -no-pad-sections -Iinclude")
    w(f"cflags = {a.cflags}")
    w("")
    w("rule as")
    w("  command = $as $asflags -o $out $in")
    w("  description = AS $in")
    if a.cc:
        w("rule cc")
        w(f"  command = {a.cc} $cflags -c -o $out.tmp.s -S $in && $as $asflags -o $out $out.tmp.s")
        w("  description = CC $in")
    w("rule ld")
    w(f"  command = $ld -EL -T config/undefined_syms_auto.txt -T config/undefined_funcs_auto.txt -T {LD_SCRIPT} -Map build/SLUS_218.55.map -o $out")
    w("  description = LD $out")
    w("rule bin")
    w("  command = $objcopy -O binary $in $out")
    w("  description = OBJCOPY $out")
    w("rule compare")
    w(f"  command = $python tools/compare.py {TARGET} $in && echo ok > $out")
    w("  description = COMPARE")
    w("")

    for o in objs:
        src = o[len("build/"):-2]  # strip build/ and .o
        if src.endswith(".c"):
            name = os.path.splitext(os.path.basename(src))[0]
            if a.cc:
                w(f"build {o}: cc {src}")
            else:
                full = f"asm/{name}.s"
                w(f"build {o}: as {full}")
        elif src.endswith(".s"):
            w(f"build {o}: as {src}")
        else:
            print("warning: unknown object source", o)
    w(f"build build/SLUS_218.55.elf: ld | {' '.join(objs)} {LD_SCRIPT}")
    w("build build/main.bin: bin build/SLUS_218.55.elf")
    w("build build/compare.ok: compare build/main.bin")
    w("default build/compare.ok")
    open("build.ninja", "w").write("\n".join(n) + "\n")
    print(f"wrote build.ninja ({len(objs)} objects)")
    if not shutil.which(x + "as") and not os.path.exists(x + "as.exe"):
        print(f"note: assembler {x}as not found; install ps2dev EE binutils (see README)")

if __name__ == "__main__":
    main()
